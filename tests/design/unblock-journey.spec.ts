import { createHmac } from 'node:crypto';
import { test, expect, activate, fixtureHeaders } from './fixtures.ts';

const base = 'https://127.0.0.1:8792';
test.use({ ignoreHTTPSErrors: true });
const localTime = (at: Date): string => new Intl.DateTimeFormat('sv-SE', { timeZone: 'Europe/Oslo', dateStyle: 'short', timeStyle: 'short' }).format(at).replace(' ', 'T');

test('Unblock: contact and schedule errors preserve work; verified payment, first call, pause, cancellation and recovery persist', async ({ page, request }, info) => {
  const phone = info.project.name === 'chromium' ? '+4792300101' : '+4792300201';
  const fixture = async (action: string, data = {}) => {
    const response = await request.post(`${base}/__test/${action}`, { headers: fixtureHeaders, data });
    expect(response.ok(), await response.text()).toBeTruthy(); return response.json();
  };
  await fixture('reset');
  await page.goto(`${base}/unblock`);
  await expect(page.getByRole('link', { name: 'Begin Unblock', exact: true }).first()).toBeVisible();
  await expect(page.locator('.hero-offer')).toContainText('up to four regular calls');
  await expect(page.locator('.hero-offer')).toContainText('including applicable VAT');
  await expect(page.locator('.hero-offer')).toContainText('opening conversation and optional light calls are included');
  await expect(page.getByRole('link', { name: 'Contact us', exact: true })).toHaveAttribute('href', 'mailto:support@example.com');
  await activate(page.getByRole('link', { name: 'Begin Unblock', exact: true }).first());
  await page.getByLabel('What shall we call you? (optional)', { exact: true }).fill('Alex');
  await page.getByLabel('Contact email (optional)', { exact: true }).fill('alex@invalid');
  await page.getByLabel('Phone number', { exact: true }).fill(phone);
  await page.getByRole('checkbox', { name: /I am currently in Norway/ }).check();
  await page.getByRole('checkbox', { name: /I’m 18 or older/ }).check();
  await activate(page.getByRole('button', { name: 'Send my verification code', exact: true }));
  await expect(page.getByLabel('Contact email (optional)', { exact: true })).toHaveAttribute('aria-invalid', 'true');
  await expect(page.getByLabel('Contact email (optional)', { exact: true })).toBeFocused();
  await expect(page.getByLabel('What shall we call you? (optional)', { exact: true })).toHaveValue('Alex');
  await expect(page.getByLabel('Phone number', { exact: true })).toHaveValue(phone);
  await page.getByLabel('Contact email (optional)', { exact: true }).fill('alex@example.com');
  await activate(page.getByRole('button', { name: 'Send my verification code', exact: true }));
  await expect(page.getByRole('button', { name: 'Send a new code', exact: true })).toBeVisible();
  const { code } = await fixture('code', { phone });
  expect(code).toMatch(/^\d{6}$/);
  await page.getByLabel('Verification code', { exact: true }).fill(code === '123456' ? '654321' : '123456');
  await activate(page.getByRole('button', { name: 'Choose my times', exact: true }));
  await expect(page.getByLabel('Verification code', { exact: true })).toHaveAttribute('aria-invalid', 'true');
  await page.getByLabel('Verification code', { exact: true }).fill(code);
  await activate(page.getByRole('button', { name: 'Choose my times', exact: true }));
  await expect(page).toHaveURL(`${base}/unblock/schedule`);
  await expect(page.getByRole('radio', { name: 'No light calls', exact: true })).toBeChecked();
  await expect(page.locator('[data-light-settings]')).toBeHidden();
  const opening = await page.getByLabel('First conversation', { exact: true }).inputValue();
  await page.getByLabel('First conversation', { exact: true }).fill(opening);
  await expect(page.getByLabel('Calls per month', { exact: true }).locator('option')).toHaveCount(4);
  await page.getByLabel('Calls per month', { exact: true }).selectOption('4');
  await page.getByLabel('Regular call · day', { exact: true }).selectOption('2');
  await page.getByLabel('Regular call · time', { exact: true }).fill('15:00');
  await expect(page.locator('[data-schedule-summary]')).toContainText('Tuesday');
  await expect(page.locator('[data-schedule-summary]')).not.toContainText('Friday');
  await activate(page.getByText('Change timezone', { exact: true }));
  await page.getByLabel('Your timezone', { exact: true }).fill('Oslo');
  await activate(page.getByRole('button', { name: 'Save my times', exact: true }));
  await expect(page.getByRole('heading', { name: 'Make room for it', exact: true })).toBeVisible();
  await expect(page.getByLabel('Your timezone', { exact: true })).toHaveValue('Oslo');
  await expect(page.getByLabel('Your timezone', { exact: true })).toBeFocused();
  await expect(page.getByLabel('First conversation', { exact: true })).toHaveValue(opening);
  await expect(page.getByLabel('Calls per month', { exact: true })).toHaveValue('4');
  await page.getByLabel('Your timezone', { exact: true }).fill('Europe/Oslo');
  await activate(page.getByRole('button', { name: 'Save my times', exact: true }));
  await expect(page.getByRole('heading', { name: 'Your chosen times', exact: true })).toBeVisible();
  await expect(page.locator('.schedule-review').filter({has:page.getByRole('heading',{name:'Your chosen times',exact:true})})).toContainText('Applicable VAT is included and itemised on your receipt');
  await expect(page.locator('.appointment')).toHaveCount(0);
  await page.getByRole('checkbox', { name: /I am currently in Norway/ }).check();
  await page.route('https://buy.stripe.com/**', route => route.fulfill({ contentType: 'text/html', body: '<p>Synthetic checkout</p>' }));
  await page.getByLabel('Email for your contract and withdrawal receipts',{exact:true}).fill('contract@example.com');
  await page.getByLabel('Confirm that email',{exact:true}).fill('contract@example.com');
  await page.getByRole('checkbox',{name:/I expressly request that my calls/}).check();
  await page.getByRole('checkbox',{name:/I have read the subscription and withdrawal information/}).check();
  await activate(page.getByRole('button', { name: 'Continue to payment', exact: true }));
  await expect(page).toHaveURL(/^https:\/\/buy\.stripe\.com\//);
  await page.goto(`${base}/unblock/account`);
  const { enrollment } = await fixture('unblock-state', { phone });
  expect(enrollment.standing).toBe('awaiting_payment');
  const payload = JSON.stringify({ id: 'evt_unblock_browser', type: 'checkout.session.completed', data: { object: {
    object: 'checkout.session', client_reference_id: enrollment.checkout_reference, subscription: 'sub_design', customer: 'cus_design', payment_status: 'paid',
  } } });
  const time = Math.floor(Date.now() / 1000);
  const signature = `t=${time},v1=${createHmac('sha256', 'design-test-webhook').update(`${time}.${payload}`).digest('hex')}`;
  const paid = await request.post(`${base}/webhooks/payments`, { data: payload, headers: { 'stripe-signature': signature } });
  expect(paid.ok(), await paid.text()).toBeTruthy();
  await fixture('unblock-information-delivered');
  await page.goto(`${base}/unblock/account`);
  await expect(page.locator('.appointment')).toBeVisible();
  await expect(page.getByRole('heading', { name: 'Ready for your first conversation', exact: true })).toBeVisible();
  await page.screenshot({ path: info.outputPath('unblock-booked.png'), fullPage: true });
  const card = await request.get(`${base}/contact.vcf`);
  expect(await card.text()).toContain('TEL;TYPE=CELL,VOICE:+4790008800');
  await expect(page.getByRole('link', { name: 'Add 8&80 to contacts', exact: true })).toBeVisible();
  await fixture('unblock-opening', { phone });
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Your next step', exact: true })).toBeVisible();
  await expect(page.locator('.current-step')).toContainText('Ask a neighbour about a sailing course');
  await page.screenshot({ path: info.outputPath('unblock-current-step.png'), fullPage: true });
  await activate(page.getByText('Move this call later', { exact: true }));
  const at = await page.locator('.appointment time').getAttribute('datetime');
  const later = localTime(new Date(Date.parse(at!) + 3600_000));
  await page.getByLabel('New time for this call', { exact: true }).fill(later);
  await activate(page.getByRole('button', { name: 'Move this call', exact: true }));
  await expect(page.getByRole('status')).toContainText('This call has moved');
  await page.reload();
  expect((await fixture('unblock-state', { phone })).enrollment.next_weekly_at).toBe(new Date(Date.parse(at!) + 3600_000).toISOString());
  await activate(page.getByRole('button', { name: 'Pause my calls', exact: true }));
  await expect(page.getByText(/Your calls are paused\. Your words stay here\. Billing continues/)).toBeVisible();
  await expect(page.locator('.appointment')).toHaveCount(0);
  expect((await fixture('unblock-state', { phone })).programme.state).toBe('paused');
  await activate(page.getByRole('button', { name: 'Resume my calls', exact: true }));
  await activate(page.getByRole('button', { name: 'Cancel at the end of this period', exact: true }));
  await expect(page).toHaveURL(`${base}/unblock/account?saved=cancel`);
  await page.reload();
  const ended = await fixture('unblock-state', { phone });
  expect(ended.enrollment.cancel_at_period_end).toBe(true); expect(ended.cancellations).toBe(1);
  await expect(page.locator('[data-seam=subscription]')).toContainText('Cancelling on');
  await activate(page.getByRole('button', { name: 'Sign out', exact: true }));
  await activate(page.getByRole('link', { name: 'Open your account', exact: true }));
  await page.getByLabel('Phone number', { exact: true }).fill(phone);
  await activate(page.getByRole('button', { name: 'Send my verification code', exact: true }));
  const verificationCode = page.getByLabel('Verification code', { exact: true });
  await expect(verificationCode).toBeVisible();
  const { code: recoveryCode } = await fixture('code', { phone });
  expect(recoveryCode).toMatch(/^\d{6}$/);
  await verificationCode.fill(recoveryCode);
  await activate(page.getByRole('button', { name: 'Open my account', exact: true }));
  await expect(page.locator('.current-step')).toContainText('Ask a neighbour about a sailing course');
  await expect(page.locator('[data-seam=subscription]')).toContainText('Cancelling on');
  const csrf=await page.locator('input[name="csrf"]').first().inputValue();
  const denied=await page.request.post(`${base}/unblock/action`,{form:{action:'withdraw',csrf:'wrong'}});expect(denied.status()).toBe(403);
  expect((await fixture('unblock-state',{phone})).enrollment.withdraw_requested_at).toBeNull();
  await page.getByRole('button',{name:'Withdraw and request a refund',exact:true}).click();
  await expect(page).toHaveURL(`${base}/unblock/account?saved=withdraw`);
  await expect(page.locator('[aria-label="Withdrawal and refund"]')).toContainText('New Unblock calls are stopped');
  await expect(page.locator('.appointment')).toHaveCount(0);
  const acknowledged=await page.request.get(`${base}/unblock/withdrawal.txt`);expect(acknowledged.ok()).toBe(true);expect(await acknowledged.text()).toContain('not confirmation that money has been refunded');
  const first=await fixture('unblock-state',{phone});
  await page.request.post(`${base}/unblock/action`,{form:{action:'withdraw',csrf}});
  expect((await fixture('unblock-state',{phone})).enrollment.withdraw_requested_at).toBe(first.enrollment.withdraw_requested_at);
  await page.reload();await expect(page.locator('[aria-label="Withdrawal and refund"]')).toContainText('Withdrawal received');
});
